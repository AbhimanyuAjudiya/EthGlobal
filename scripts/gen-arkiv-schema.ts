/**
 * `pnpm schema:gen` writes docs/arkiv.schema.json; `pnpm schema:check` fails when it differs from the generator
 * (BUILD-PLAN §5.1 "generated artefacts"). One source: the ledger payload schemas of `@ethglobal/protocol/schemas`
 * (INTERFACES §1.4) through zod 4's `z.toJSONSchema` (JSON Schema 2020-12, as services/api/openapi.json does), plus
 * the per-type Arkiv facts a reviewer needs next to them: the indexed annotations, `expiresIn`, the attribute
 * mapping of `packages/adapters/src/live/arkiv-ledger.ts` (key → logicalKey, expiresAt/day as u64) and the
 * `recharge.<type>.v1` schema names.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { isDeepStrictEqual } from 'node:util';

import { z } from 'zod';

import * as ids from '@ethglobal/protocol/ids';
import * as schemas from '@ethglobal/protocol/schemas';

const FILE = join(import.meta.dirname, '..', 'docs', 'arkiv.schema.json');

/** Payload schema export per entity type (ids.ENTITY_TYPES is the list; a new type without a row fails the run). */
const PAYLOAD: Record<string, string> = {
  entitlement: 'entitlementSchema',
  campaign: 'campaignSchema',
  gift: 'giftSchema',
  nonce: 'nonceSchema',
  receipt: 'receiptSchema',
  agentpolicy: 'agentPolicySchema',
  claim: 'claimSchema',
};

const nonceTtl = Number((ids as Record<string, unknown>).NONCE_TTL_S ?? ids.CHALLENGE_TTL_S);
/** The annotation sets and lifetimes written by @ethglobal/octroi/store (documented beside each protocol schema). */
const ARKIV: Record<string, { annotations: string[]; expiresIn: string }> = {
  entitlement: {
    annotations: [
      'type',
      'key',
      'kind',
      'status',
      'tier',
      'campaignId?',
      'iccidHash?',
      'expiresAt',
    ],
    expiresIn: 'secondsUntil(expiresAt) — the plan validity (7 d by default)',
  },
  campaign: {
    annotations: ['type', 'key', 'sponsor', 'expiresAt'],
    expiresIn: 'secondsUntil(expiresAt) — the on-chain campaign expiry',
  },
  gift: {
    annotations: [
      'type',
      'key',
      'kind',
      'state',
      'namehash?',
      'pinKey',
      'serial',
      'campaignId?',
      'expiresAt',
    ],
    expiresIn: `secondsUntil(claimBy) — GIFT_CLAIM_WINDOW_S = ${ids.GIFT_CLAIM_WINDOW_S} s`,
  },
  nonce: {
    annotations: ['type', 'key', 'nonce'],
    expiresIn: `${nonceTtl} s (written on consume)`,
  },
  receipt: {
    annotations: ['type', 'key', 'receiptKind', 'entitlementKeyHash', 'campaignId?', 'day'],
    expiresIn: `RECEIPT_TTL_S = ${ids.RECEIPT_TTL_S} s`,
  },
  agentpolicy: {
    annotations: ['type', 'key', 'owner'],
    expiresIn: `AGENT_POLICY_TTL_S = ${ids.AGENT_POLICY_TTL_S} s`,
  },
  claim: {
    annotations: ['type', 'key', 'expiresAt'],
    expiresIn: 'secondsUntil(expiresAt) — create-if-absent lock',
  },
};

export function arkivSchemaDocument(): Record<string, unknown> {
  const defs: Record<string, unknown> = {};
  for (const type of ids.ENTITY_TYPES) {
    const name = PAYLOAD[type];
    const schema = name === undefined ? undefined : (schemas as Record<string, unknown>)[name];
    const arkiv = ARKIV[type];
    if (!(schema instanceof z.ZodType) || arkiv === undefined)
      throw new Error(
        `entity type "${type}" has no payload schema / Arkiv row in gen-arkiv-schema.ts`,
      );
    const { $schema: _drop, ...json } = z.toJSONSchema(schema, {
      target: 'draft-2020-12',
      io: 'output',
      unrepresentable: 'any',
    }) as Record<string, unknown>;
    defs[type] = {
      ...json,
      'x-arkiv': {
        schemaName: `recharge.${type}.v1`,
        annotations: arkiv.annotations,
        expiresIn: arkiv.expiresIn,
      },
    };
  }
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: 'urn:recharge:arkiv-schema:v1',
    title: 'Recharge — Arkiv entity payloads',
    description:
      'Every Recharge entity on Arkiv (rabdi, chain 7794095) is { payload: JSON.stringify(<one of $defs>), ' +
      'attributes: <x-arkiv.annotations>, expiresIn: <x-arkiv.expiresIn> }. Payloads are world-readable: nothing in ' +
      'them is secret (no ICCID, LPA, nullifier, PIN or capability key). Generated by scripts/gen-arkiv-schema.ts ' +
      'from @ethglobal/protocol/schemas; do not edit by hand.',
    'x-arkiv': {
      chainId: 7_794_095,
      attributeMapping: {
        key: 'logicalKey (key is a reserved word of the Arkiv query language, AL-2)',
        expiresAt: 'u64',
        day: 'u64',
        other: 'str',
        payload: 'bytes (UTF-8 JSON, ≤ 128 KiB)',
        createdAtMs: 'u64',
      },
      everyReadFilters: '$creator = the API writer (T-79)',
      expiryRounding:
        'expiresIn seconds → ExpirationTime.fromSeconds: whole 2-s blocks, rounded up; ≤ 7 884 000 blocks (A-24)',
    },
    oneOf: ids.ENTITY_TYPES.map((t) => ({ $ref: `#/$defs/${t}` })),
    $defs: defs,
  };
}

const document = arkivSchemaDocument();
if (process.argv.includes('--check')) {
  // compared as data: prettier may re-wrap the committed file
  const committed: unknown = JSON.parse(readFileSync(FILE, 'utf8'));
  if (!isDeepStrictEqual(committed, document)) {
    console.error('docs/arkiv.schema.json is stale: run pnpm schema:gen');
    process.exit(1);
  }
  console.log('docs/arkiv.schema.json is up to date');
} else {
  writeFileSync(FILE, `${JSON.stringify(document, null, 2)}\n`);
  console.log(`wrote docs/arkiv.schema.json (${ids.ENTITY_TYPES.length} entity types)`);
}
