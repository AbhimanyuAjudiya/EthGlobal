#!/usr/bin/env bash
# Regenerates security/redteam/findings/INDEX.md from the YAML front matter of RT-*.md and DRILL-*.md files.
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../findings" && pwd)"
OUT="$DIR/INDEX.md"
{
  echo "# Findings index (generated by tools/findings-index.sh — do not edit)"
  echo
  echo "| id | severity | status | module | threat | title |"
  echo "|---|---|---|---|---|---|"
  for f in "$DIR"/RT-*.md "$DIR"/DRILL-*.md; do
    [[ -f "$f" ]] || continue
    get() { awk -v k="$1" 'BEGIN{fm=0} /^---[[:space:]]*$/{fm++; next} fm==1 && $0 ~ "^"k":" {sub("^"k":[[:space:]]*",""); print; exit}' "$f"; }
    printf '| [%s](%s) | %s | %s | %s | %s | %s |\n' "$(get id)" "$(basename "$f")" "$(get severity)" "$(get status)" "$(get module)" "$(get threat)" "$(get title)"
  done
} > "$OUT"
echo "wrote $OUT"
